//! Regenerates the Swift and C half of the bridge from the declarations.
//!
//! The generated half is its own Swift module, `FlowsBridge`, so the raw
//! pointers swift-bridge writes stay out of the app module. Two things are
//! added here for that: a module map that names the C declarations
//! `FlowsBridgeC`, and one `import FlowsBridgeC` line at the top of each
//! generated Swift file (a module has no bridging header to pull them in).
//!
//! Output is written to a scratch directory first and copied into
//! `apple/FLOWS/RustBridge/` only when a file's bytes changed, so a rebuild
//! does not touch timestamps and make Xcode recompile. The generated files are
//! committed and never hand-edited (3.25.5); CI regenerates and fails on any
//! difference.

#![forbid(unsafe_code)]

use std::fs;
use std::path::{Path, PathBuf};

const BRIDGES: &[&str] = &[
    "src/airports.rs",
    "src/alert_text.rs",
    "src/alerts.rs",
    "src/climate.rs",
    "src/forecast.rs",
    "src/geo.rs",
    "src/hazard_feeds.rs",
    "src/learning.rs",
    "src/long_trips.rs",
    "src/modes.rs",
    "src/places.rs",
    "src/places_text.rs",
    "src/recents_and_rides.rs",
    "src/risk.rs",
    "src/risk_field.rs",
    "src/seasonal.rs",
    "src/tags_and_replies.rs",
    "src/transit.rs",
    "src/trip_vehicle.rs",
    "src/vehicle_policy.rs",
];

fn copy_if_changed(from: &Path, to: &Path) -> std::io::Result<()> {
    for entry in fs::read_dir(from)? {
        let entry = entry?;
        let src = entry.path();
        let dst = to.join(entry.file_name());
        if src.is_dir() {
            fs::create_dir_all(&dst)?;
            copy_if_changed(&src, &dst)?;
        } else {
            let new = fs::read(&src)?;
            if fs::read(&dst).ok().as_deref() != Some(new.as_slice()) {
                fs::write(&dst, new)?;
            }
        }
    }
    Ok(())
}

/// The C half as a module the Swift half and the app can import.
const MODULE_MAP: &str = "\
// Generated by rust/flows-bridge/build.rs. Do not edit.
module FlowsBridgeC {
    header \"SwiftBridgeCore.h\"
    header \"flows-bridge/flows-bridge.h\"
    export *
}
";

/// Put `import FlowsBridgeC` on the first line of a generated Swift file.
fn import_c_module(file: &Path) -> std::io::Result<()> {
    let text = fs::read_to_string(file)?;
    fs::write(file, format!("import FlowsBridgeC\n{text}"))
}

/// swift-bridge gives the C struct `RustStr` two Swift conformances. Now
/// that the struct comes from another module (FlowsBridgeC), Swift wants
/// each one marked `@retroactive`, and warns otherwise. Both modules are
/// generated here together, so the mark is true. Fails if swift-bridge's
/// output no longer has exactly these two lines.
fn mark_retroactive(file: &Path) -> std::io::Result<()> {
    let mut text = fs::read_to_string(file)?;
    for conformance in ["Identifiable", "Equatable"] {
        let plain = format!("extension RustStr: {conformance} {{");
        assert_eq!(
            text.matches(&plain).count(),
            1,
            "swift-bridge's output changed: {plain}"
        );
        text = text.replace(
            &plain,
            &format!("extension RustStr: @retroactive {conformance} {{"),
        );
    }
    fs::write(file, text)
}

fn main() {
    for b in BRIDGES {
        println!("cargo:rerun-if-changed={b}");
    }
    let manifest = PathBuf::from(env!("CARGO_MANIFEST_DIR"));
    let out = PathBuf::from(std::env::var("OUT_DIR").expect("cargo sets OUT_DIR")).join("swift");
    let _ = fs::remove_dir_all(&out);
    swift_bridge_build::parse_bridges(BRIDGES.iter().map(|b| manifest.join(b)))
        .write_all_concatenated(&out, env!("CARGO_PKG_NAME"));
    import_c_module(&out.join("SwiftBridgeCore.swift")).expect("mark SwiftBridgeCore.swift");
    mark_retroactive(&out.join("SwiftBridgeCore.swift")).expect("mark the RustStr conformances");
    import_c_module(
        &out.join(env!("CARGO_PKG_NAME"))
            .join(concat!(env!("CARGO_PKG_NAME"), ".swift")),
    )
    .expect("mark the generated bridge");
    fs::write(out.join("module.modulemap"), MODULE_MAP).expect("write the module map");
    let dest = manifest.join("../../apple/FLOWS/RustBridge");
    fs::create_dir_all(&dest).expect("create apple/FLOWS/RustBridge");
    copy_if_changed(&out, &dest).expect("copy generated bindings");
}
