fn copy_if_changed(from: &Path, to: &Path) -> std::io::Result<()> {
    for entry in fs::read_dir(from)? {
        let entry = entry?;
        let src = entry.path();
        let dst = to.join(entry.file_name());
        if src.is_dir() {
            fs::create_dir_all(&dst)?;
            copy_if_changed(&src, &dst)?;
        } else {
            let new = fs::read(&src)?;
            if fs::read(&dst).ok().as_deref() != Some(new.as_slice()) {
                fs::write(&dst, new)?;
            }
        }
    }
    Ok(())
}

/// The C half as a module the Swift half and the app can import.
const MODULE_MAP: &str = "\
// Generated by rust/flows-bridge/build.rs. Do not edit.
module FlowsBridgeC {
    header \"SwiftBridgeCore.h\"
    header \"flows-bridge/flows-bridge.h\"
    export *
}
";

/// Put `import FlowsBridgeC` on the first line of a generated Swift file.
fn import_c_module(file: &Path) -> std::io::Result<()> {
    let text = fs::read_to_string(file)?;
    fs::write(file, format!("import FlowsBridgeC\n{text}"))
}

/// swift-bridge gives the C struct `RustStr` two Swift conformances. Now
/// that the struct comes from another module (FlowsBridgeC), Swift wants
/// each one marked `@retroactive`, and warns otherwise. Both modules are
/// generated here together, so the mark is true. Fails if swift-bridge's
/// output no longer has exactly these two lines.
fn mark_retroactive(file: &Path) -> std::io::Result<()> {
    let mut text = fs::read_to_string(file)?;
    for conformance in ["Identifiable", "Equatable"] {
        let plain = format!("extension RustStr: {conformance} {{");
        assert_eq!(
            text.matches(&plain).count(),
            1,
            "swift-bridge's output changed: {plain}"
        );
        text = text.replace(
            &plain,
            &format!("extension RustStr: @retroactive {conformance} {{"),
        );
    }
    fs::write(file, text)
}

/// The head of the safe overloads file.
const SAFE_HEAD: &str = "\
// Generated by rust/flows-bridge/build.rs. Do not edit.
//
// Safe doors into the bridge. swift-bridge writes every slice parameter as
// an `UnsafeBufferPointer`, which would put raw memory in the hands of each
// caller. For every such function this file adds a twin that takes `Span`,
// the standard library's checked, non-escaping view of an array's storage.
// The app calls the twins only, so it holds no raw pointer.
//
// Rust builds a slice from the address and the count, and a slice from a
// null address is undefined even at count zero. An empty span may have no
// address, so `_flowsLend` gives an empty loan a non-null, aligned one
// (what Rust itself uses for an empty slice). Nothing is read through it.
// It is public only so the tests can see that address; app code builds with
// strict memory safety, where touching the pointer it hands out is an error.

@inline(__always)
public func _flowsLend<Element, Result>(
    _ span: Span<Element>, _ body: (UnsafeBufferPointer<Element>) -> Result
) -> Result {
    span.withUnsafeBufferPointer { loan in
        if loan.baseAddress != nil { return body(loan) }
        let aligned = UnsafePointer<Element>(bitPattern: MemoryLayout<Element>.alignment)
        return body(UnsafeBufferPointer(start: aligned, count: 0))
    }
}
";

/// Split a parameter list on the commas between parameters (not the ones
/// inside `<...>`).
fn split_params(params: &str) -> Vec<&str> {
    let mut parts = Vec::new();
    let (mut depth, mut start) = (0usize, 0usize);
    for (i, c) in params.char_indices() {
        match c {
            '<' => depth += 1,
            '>' => depth = depth.saturating_sub(1),
            ',' if depth == 0 => {
                parts.push(params[start..i].trim());
                start = i + 1;
            }
            _ => {}
        }
    }
    if !params[start..].trim().is_empty() {
        parts.push(params[start..].trim());
    }
    parts
}

/// One safe twin for a generated `public func` line that takes a buffer.
/// `indent` is four spaces for a method. Panics on a shape it does not
/// know, so a swift-bridge upgrade cannot leave a function without a twin.
fn safe_twin(line: &str, method: bool) -> String {
    const BUFFER: &str = "UnsafeBufferPointer<";
    let pad = if method { "    " } else { "" };
    let decl = line
        .trim()
        .strip_suffix(" {")
        .unwrap_or_else(|| panic!("swift-bridge's output changed: {line}"));
    let open = decl.find('(').expect("a parameter list");
    let close = decl.rfind(')').expect("a parameter list");
    let head = &decl[..open];
    let name = head
        .trim_start_matches("public func ")
        .split('<')
        .next()
        .expect("a function name");
    let after = decl[close + 1..].trim();
    let result = match after.strip_prefix("->") {
        Some(r) => r.trim().to_string(),
        None => {
            assert!(after.is_empty(), "swift-bridge's output changed: {line}");
            "()".to_string()
        }
    };
    let mut safe_params = Vec::new();
    let mut args = Vec::new();
    let mut loans = Vec::new();
    for p in split_params(&decl[open + 1..close]) {
        let (label, ty) = p
            .strip_prefix("_ ")
            .and_then(|p| p.split_once(": "))
            .unwrap_or_else(|| panic!("swift-bridge's output changed: {line}"));
        args.push(label);
        if let Some(element) = ty.strip_prefix(BUFFER) {
            let element = element.strip_suffix('>').expect("a buffer element");
            safe_params.push(format!("_ {label}: Span<{element}>"));
            loans.push((label, element));
        } else {
            assert!(
                !ty.contains("Unsafe"),
                "swift-bridge's output changed: {line}"
            );
            safe_params.push(p.to_string());
        }
    }
    let receiver = if method { "self." } else { "" };
    let mut body = format!("{receiver}{name}({})", args.join(", "));
    for (label, element) in loans.iter().rev() {
        body = format!(
            "_flowsLend({label}) {{ ({label}: UnsafeBufferPointer<{element}>) -> {result} in {body} }}"
        );
    }
    let arrow = if result == "()" {
        String::new()
    } else {
        format!(" -> {result}")
    };
    format!(
        "{pad}{head}({}){arrow} {{\n{pad}    {body}\n{pad}}}\n",
        safe_params.join(", ")
    )
}

/// The safe overloads file for the generated bridge text.
fn safe_overloads(bridge: &str) -> String {
    let mut out = String::from(SAFE_HEAD);
    let mut owner: Option<&str> = None;
    let mut open_owner: Option<&str> = None;
    let mut twins = 0usize;
    for line in bridge.lines() {
        if let Some(rest) = line.strip_prefix("extension ") {
            owner = rest.split([' ', ':']).next();
        } else if line.starts_with("public class ") || line.starts_with("public func ") {
            owner = None;
        }
        if !line.contains("public func ") || !line.contains("UnsafeBufferPointer<") {
            continue;
        }
        let method = line.starts_with("    public func ");
        assert!(
            method || line.starts_with("public func "),
            "swift-bridge's output changed: {line}"
        );
        let wanted = if method {
            Some(owner.unwrap_or_else(|| panic!("a method outside an extension: {line}")))
        } else {
            None
        };
        if open_owner != wanted {
            if open_owner.is_some() {
                out.push_str("}\n");
            }
            if let Some(w) = wanted {
                out.push_str(&format!("\nextension {w} {{\n"));
            }
            open_owner = wanted;
        }
        if !method {
            out.push('\n');
        }
        out.push_str(&safe_twin(line, method));
        twins += 1;
    }
    if open_owner.is_some() {
        out.push_str("}\n");
    }
    assert_eq!(
        twins,
        bridge
            .lines()
            .filter(|l| l.contains("UnsafeBufferPointer<"))
            .count(),
        "a buffer appears somewhere a safe twin does not cover"
    );
    out
}

fn main() {
    for b in BRIDGES {
        println!("cargo:rerun-if-changed={b}");
    }
    let manifest = PathBuf::from(env!("CARGO_MANIFEST_DIR"));
    let out = PathBuf::from(std::env::var("OUT_DIR").expect("cargo sets OUT_DIR")).join("swift");
    let _ = fs::remove_dir_all(&out);
    swift_bridge_build::parse_bridges(BRIDGES.iter().map(|b| manifest.join(b)))
        .write_all_concatenated(&out, env!("CARGO_PKG_NAME"));
    import_c_module(&out.join("SwiftBridgeCore.swift")).expect("mark SwiftBridgeCore.swift");
    mark_retroactive(&out.join("SwiftBridgeCore.swift")).expect("mark the RustStr conformances");
    import_c_module(
        &out.join(env!("CARGO_PKG_NAME"))
            .join(concat!(env!("CARGO_PKG_NAME"), ".swift")),
    )
    .expect("mark the generated bridge");
    fs::write(out.join("module.modulemap"), MODULE_MAP).expect("write the module map");
    let bridge_dir = out.join(env!("CARGO_PKG_NAME"));
    let bridge = fs::read_to_string(bridge_dir.join(concat!(env!("CARGO_PKG_NAME"), ".swift")))
        .expect("read the generated bridge");
    fs::write(
        bridge_dir.join(concat!(env!("CARGO_PKG_NAME"), "-safe.swift")),
        format!("import FlowsBridgeC\n{}", safe_overloads(&bridge)),
    )
    .expect("write the safe overloads");
    let dest = manifest.join("../../apple/FLOWS/RustBridge");
    fs::create_dir_all(&dest).expect("create apple/FLOWS/RustBridge");
    copy_if_changed(&out, &dest).expect("copy generated bindings");
}
