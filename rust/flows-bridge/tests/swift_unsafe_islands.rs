//! Swift's unsafe tools live in one folder, `apple/FLOWS/Sources/Core/Islands`.
//!
//! Swift proves memory and data-race safety for most code. The tools that
//! switch a proof off (`@unchecked Sendable`, `nonisolated(unsafe)`,
//! `Unmanaged`, unchecked locks, raw pointers and buffer loans) are allowed only in the
//! island files, where each use states the promise it rests on. This walks
//! every hand-written Swift file and fails on one of those tools anywhere
//! else, so the islands cannot quietly spread. The generated bridge
//! (`RustBridge`) is swift-bridge's output, not hand-written, and is the
//! boundary the bridge crate already owns.

use std::path::{Path, PathBuf};

/// Where hand-written Swift lives.
const SWIFT_ROOTS: &[&str] = &["apple/FLOWS/Sources", "apple/FLOWSWatch"];

/// The islands: the only folder where the tools below may appear.
const ISLANDS: &str = "apple/FLOWS/Sources/Core/Islands";

/// Generated by swift-bridge on every build; never hand-edited.
const GENERATED: &[&str] = &["apple/FLOWS/RustBridge", "apple/FLOWS/Generated"];

/// The tools that switch a safety proof off, and the generated `toString()`
/// that traps on empty Rust text (the islands read text through `.text`).
///
/// The test target is not walked: its fixtures build raw bytes by hand.
const TOOLS: &[&str] = &[
    "@unchecked",
    "nonisolated(unsafe)",
    "unowned(unsafe)",
    "Unmanaged",
    "unsafeBitCast",
    "unsafeDowncast",
    "uncheckedState",
    "withLockUnchecked",
    "UnsafeContinuation",
    "withUnsafe",
    "UnsafePointer",
    "UnsafeMutablePointer",
    "UnsafeRawPointer",
    "UnsafeMutableRawPointer",
    "UnsafeBufferPointer",
    "UnsafeMutableBufferPointer",
    "UnsafeRawBufferPointer",
    "UnsafeMutableRawBufferPointer",
    "bindMemory",
    "assumingMemoryBound",
    "baseAddress",
    ".toString()",
];

fn repo() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("../..")
        .canonicalize()
        .expect("repository root")
}

/// The code on a line: what is left of a `//` comment. A `//` inside a
/// string (a URL) cuts the line short too, which can only hide the rest of
/// that one line; `the_check_sees_what_it_should` pins what is caught.
fn code(line: &str) -> &str {
    match line.find("//") {
        Some(at) if !line[..at].ends_with(':') => &line[..at],
        _ => line,
    }
}

/// The tools one file's text uses, as `line number: tool`.
fn tools_in(text: &str) -> Vec<String> {
    let mut found = Vec::new();
    let mut in_block_comment = false;
    for (n, line) in text.lines().enumerate() {
        let mut rest = line;
        let mut kept = String::new();
        loop {
            if in_block_comment {
                match rest.find("*/") {
                    Some(at) => {
                        rest = &rest[at + 2..];
                        in_block_comment = false;
                    }
                    None => break,
                }
            } else {
                match rest.find("/*") {
                    Some(at) => {
                        kept.push_str(&rest[..at]);
                        rest = &rest[at + 2..];
                        in_block_comment = true;
                    }
                    None => {
                        kept.push_str(rest);
                        break;
                    }
                }
            }
        }
        let kept = code(&kept);
        for tool in TOOLS {
            if kept.contains(tool) {
                found.push(format!("{}: {tool}", n + 1));
            }
        }
    }
    found
}

fn swift_files(dir: &Path, out: &mut Vec<PathBuf>) {
    let entries = std::fs::read_dir(dir).unwrap_or_else(|e| panic!("{}: {e}", dir.display()));
    for entry in entries {
        let path = entry.expect("directory entry").path();
        if path.is_dir() {
            swift_files(&path, out);
        } else if path.extension().and_then(|e| e.to_str()) == Some("swift") {
            out.push(path);
        }
    }
}

#[test]
fn unsafe_swift_stays_in_the_islands() {
    let root = repo();
    let islands = root.join(ISLANDS);
    let mut files = Vec::new();
    for dir in SWIFT_ROOTS {
        swift_files(&root.join(dir), &mut files);
    }
    assert!(files.len() > 100, "found only {} Swift files", files.len());
    let mut found = Vec::new();
    let mut island_uses = 0;
    for path in &files {
        if GENERATED.iter().any(|g| path.starts_with(root.join(g))) {
            continue;
        }
        let text =
            std::fs::read_to_string(path).unwrap_or_else(|e| panic!("{}: {e}", path.display()));
        let uses = tools_in(&text);
        if path.starts_with(&islands) {
            island_uses += uses.len();
            continue;
        }
        let rel = path.strip_prefix(&root).expect("under the root").display();
        found.extend(uses.into_iter().map(|u| format!("{rel}:{u}")));
    }
    // The walk is looking in the right place: the islands do hold the tools.
    assert!(
        island_uses > 0,
        "{ISLANDS} holds no unsafe tool; has it moved?"
    );
    assert!(
        found.is_empty(),
        "unsafe Swift outside {ISLANDS} ({}):\n{}",
        found.len(),
        found.join("\n")
    );
}

#[test]
fn the_check_sees_what_it_should() {
    let caught = |text: &str| !tools_in(text).is_empty();
    assert!(caught("final class A: @unchecked Sendable {}"));
    assert!(caught("    nonisolated(unsafe) static var x = 0"));
    assert!(caught("let p = Unmanaged.passRetained(box)"));
    assert!(caught("out.withUnsafeMutableBytes { f($0) }"));
    assert!(caught("OSAllocatedUnfairLock(uncheckedState: box)"));
    assert!(caught("xs.withUnsafeBufferPointer { f($0) }"));
    assert!(caught("func f(_ p: UnsafeBufferPointer<UInt8>)"));
    assert!(caught("let kind = flows_kind(event).toString()"));
    assert!(caught(
        "let u = URL(string: \"https://x.test\"); y.withLockUnchecked { _ in }"
    ));
    assert!(caught("/* note */ let q = unsafeBitCast(a, to: B.self)"));
    // Words about the tools are not uses of them.
    assert!(!caught("// `nonisolated(unsafe)` used to sit here"));
    assert!(!caught("/// was @unchecked Sendable"));
    assert!(!caught(
        "/* withLockUnchecked\n   Unmanaged */\nlet safe = 1"
    ));
    assert!(!caught("xs.lent { flows_sum($0) }"));
    assert!(!caught("let kind = flows_kind(event).text"));
    assert!(!caught("let safe = [1, 2, 3].map { $0 + 1 }"));
}
